// src/utils/ocrFileGenerator.ts
import { formatOCRText } from './ocr';

export interface OCRFileOptions {
  fileName: string;
  documentTitle: string;
  extractedText: string;
  confidence: number;
  timestamp: string;
  documentId: number;
}

/**
 * Generate a text file content from OCR results
 */
export const generateOCRTextFile = (options: OCRFileOptions): string => {
  const { fileName, documentTitle, extractedText, confidence, timestamp, documentId } = options;
  
  // Create a formatted text file content
  const content = `==================================================
OCR EXTRACTED TEXT
==================================================

Document: ${documentTitle}
Original File: ${fileName}
Document ID: ${documentId}
Extracted On: ${timestamp}
Confidence Score: ${Math.round(confidence)}%

--------------------------------------------------
EXTRACTED TEXT
--------------------------------------------------

${extractedText}

--------------------------------------------------
END OF EXTRACTED TEXT
==================================================
`;
  
  return content;
};

/**
 * Generate a markdown file from OCR results
 */
export const generateOCRMarkdownFile = (options: OCRFileOptions): string => {
  const { fileName, documentTitle, extractedText, confidence, timestamp, documentId } = options;
  
  return `# OCR Extracted Text

## Document Information
- **Document:** ${documentTitle}
- **Original File:** ${fileName}
- **Document ID:** ${documentId}
- **Extracted On:** ${timestamp}
- **Confidence Score:** ${Math.round(confidence)}%

## Extracted Text

\`\`\`
${extractedText}
\`\`\`

---
*Generated by NSTP Office System OCR Module*
`;
};

/**
 * Generate a JSON file from OCR results
 */
export const generateOCRJSONFile = (options: OCRFileOptions): string => {
  const { fileName, documentTitle, extractedText, confidence, timestamp, documentId } = options;
  
  const data = {
    document: {
      id: documentId,
      title: documentTitle,
      original_file: fileName,
      extracted_at: timestamp,
      confidence_score: Math.round(confidence),
    },
    extracted_text: extractedText,
    metadata: {
      word_count: extractedText.split(/\s+/).length,
      char_count: extractedText.length,
      line_count: extractedText.split('\n').length,
    }
  };
  
  return JSON.stringify(data, null, 2);
};

/**
 * Download OCR text as a file
 */
export const downloadOCRFile = (
  text: string, 
  fileName: string, 
  format: 'txt' | 'md' | 'json' = 'txt'
): void => {
  const extensions = {
    txt: 'txt',
    md: 'md',
    json: 'json',
  };
  
  const blob = new Blob([text], { 
    type: format === 'json' 
      ? 'application/json' 
      : format === 'md' 
        ? 'text/markdown' 
        : 'text/plain' 
  });
  
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `${fileName}_ocr.${extensions[format]}`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
};

/**
 * Save OCR text to localStorage cache
 */
export const saveOCRToCache = (
  documentId: number, 
  text: string, 
  confidence: number
): void => {
  const cache = JSON.parse(localStorage.getItem('ocr_cache') || '{}');
  cache[documentId] = {
    text,
    confidence,
    timestamp: Date.now(),
  };
  localStorage.setItem('ocr_cache', JSON.stringify(cache));
};

/**
 * Get OCR text from cache
 */
export const getOCRFromCache = (documentId: number): { text: string; confidence: number; timestamp: number } | null => {
  const cache = JSON.parse(localStorage.getItem('ocr_cache') || '{}');
  return cache[documentId] || null;
};